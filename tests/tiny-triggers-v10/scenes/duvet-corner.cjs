'use strict';
module.exports = async function (page, io, assert) {
  assert.equal((await io.state()).phase, 'insert');
  await io.drag([267, 147], [343, 211]); // A corner cannot be fixed before insertion.
  assert.equal((await io.state()).insertion, 0);
  await io.down(240, 241);
  await io.move(240, 186);
  await io.until((state) => state.insertion > 0.3);
  assert((await io.state()).insertion < 0.6);
  await io.shot('inserting');
  await io.move(240, 126);
  await io.up();
  await io.until((state) => state.phase === 'shake');
  await io.down(240, 211);
  await io.wait(250);
  assert.equal((await io.state()).shakes, 0, 'Holding the cover does not count as shaking it');
  await io.move(300, 211);
  await io.wait(70);
  await io.move(350, 211);
  await io.wait(70);
  assert.equal((await io.state()).shakes, 1, 'A one-way drag cannot count as repeated shakes');
  await io.move(180, 211);
  await io.wait(70);
  await io.move(300, 211);
  await io.wait(70);
  assert.equal((await io.state()).alignedCorners, 3);
  assert.equal(await page.evaluate(() => finished), false);
  await io.move(180, 211);
  await io.wait(70);
  await io.up();
  await io.until((state) => state.phase === 'fix');
  await io.shot('three-corners');
  await io.click(343, 211);
  assert.equal((await io.state()).phase, 'fix', 'Clicking the empty corner cannot transport the stuffing');
  await io.down(267, 147);
  await io.move(305, 179);
  assert((await io.state()).fix > 0.3 && (await io.state()).fix < 0.7);
  await io.shot('fixing');
  await io.move(343, 211);
  await io.up();
  await io.until((state) => state.phase === 'slipping' && state.slip > 0.2 && state.slip < 0.8);
  assert.equal(await page.evaluate(() => finished), false, 'Opposite-corner slip must animate before completion');
  await io.shot('opposite-slipping');
  await io.until((state) => state.phase === 'done');
  const final = await io.state();
  assert.equal(final.fix, 1);
  assert(final.oppositeSlipped);
  assert.equal(final.alignedCorners, 3);
  assert.equal(await page.evaluate(() => finished), true);
  await io.shot('opposite-out');
  // The shared runner verifies Retry restores the separate duvet and cover.
};
