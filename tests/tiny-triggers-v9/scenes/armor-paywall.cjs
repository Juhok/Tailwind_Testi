module.exports = async function (page, io, assert) {
  let state = await io.state();
  assert.equal(state.health, 20);
  assert.equal(state.equipped, false);
  await io.drag([329, 148], [116, 156]);
  await io.click(240, 165);
  state = await io.state();
  assert.equal(state.phase, 0, 'Armor and paywall cannot be reached before battle');
  assert.equal(state.health, 20);
  assert.equal(state.finished, false);

  await io.drag([145, 145], [330, 150]);
  state = await io.state();
  assert.equal(state.health, 19, 'Dragging the sword strikes the sentinel once');
  assert.equal(state.attacks, 1);
  await io.wait(450);
  await io.down(414, 224);
  await io.until(s => s.attacks >= 7);
  state = await io.state();
  assert.equal(state.phase, 0, 'A real battle precedes the reward');
  assert.ok(state.health > 0 && state.health < 15);
  assert.equal(state.equipped, false);
  assert.equal(state.popupVisible, false);
  await io.shot('armor-paywall-battle');
  await io.until(s => s.phase === 1);
  await io.up();
  state = await io.state();
  assert.equal(state.health, 0);
  assert.equal(state.attacks, 20);
  assert.equal(state.equipped, false);
  assert.equal(state.finished, false);
  await io.until(s => s.phase === 2);
  await io.shot('armor-paywall-reward');

  await io.click(329, 148);
  await io.drag([329, 148], [390, 90]);
  state = await io.state();
  assert.equal(state.phase, 2, 'Clicking or dropping armor away from the knight cannot equip it');
  assert.equal(state.equipped, false);
  assert.equal(state.popupVisible, false);
  assert.equal(state.armor.x, 329, 'An incorrect drop returns the physical prize');
  await io.drag([329, 148], [116, 156], { steps: 20 });
  state = await io.state();
  assert.equal(state.phase, 3);
  assert.equal(state.popupVisible, false);
  await io.until(s => s.phase === 4);
  state = await io.state();
  assert.equal(state.equipped, true, 'The golden suit is visibly equipped before interruption');
  assert.equal(state.popupVisible, false);
  assert.equal(state.finished, false);
  await io.shot('armor-paywall-equipped');
  await io.until(s => s.finished);
  state = await io.state();
  assert.equal(state.popupVisible, true);
  assert.equal(state.popupTitle, 'Your playtime has expired.');
  assert.equal(state.popupCta, 'Continue playing — €12.99.');
  assert.ok(state.revealTime >= 1, 'The armor has a visible reveal before the paywall');
  assert.equal(await page.evaluate(() => finished), true);
  await io.shot('armor-paywall-expired');
};
