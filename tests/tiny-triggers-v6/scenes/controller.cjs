module.exports = async function (page, io, assert) {
  let state = await io.state();
  assert.equal(state.bossHealth, 6);
  assert.equal(state.connected, true);
  await io.click(154, 216);
  await io.click(330, 112);
  await io.down(339, 218);
  await io.move(430, 218);
  await io.up();
  state = await io.state();
  assert.equal(state.successfulAttacks, 0, 'Wrong controls, clicking the game, and canceled presses cannot attack');
  assert.equal(state.bossHealth, 6);
  assert.ok(state.canceledPresses >= 1);
  await io.click(339, 218);
  state = await io.state();
  assert.equal(state.successfulAttacks, 1);
  assert.equal(state.bossHealth, 5);
  assert.equal(state.finished, false);
  await io.down(339, 218);
  await io.until(s => s.successfulAttacks >= 3);
  await io.up();
  state = await io.state();
  assert.equal(state.phase, 0);
  assert.ok(state.bossHealth > 1 && state.bossHealth < 5);
  assert.equal(state.connected, true);
  await io.shot('controller-fight-progress');

  await io.down(339, 218);
  await io.until(s => s.phase === 1);
  await io.up();
  state = await io.state();
  assert.equal(state.bossHealth, 1);
  assert.equal(state.successfulAttacks, 5);
  assert.equal(state.failedAttacks, 0);
  assert.equal(state.connected, true, 'The controller works until the final input');
  assert.equal(state.finished, false);
  await io.wait(650);
  assert.equal((await io.state()).bossHealth, 1, 'The finishing hit requires a fresh press');
  await io.shot('controller-one-hit-left');

  await io.down(339, 218);
  await io.wait(650);
  assert.equal((await io.state()).connected, true, 'The finishing attempt waits for release so it remains cancelable');
  await io.move(430, 218);
  await io.up();
  assert.equal((await io.state()).connected, true, 'A canceled final press does not trigger the disconnect');
  await io.click(339, 218);
  state = await io.state();
  assert.equal(state.phase, 2);
  assert.equal(state.connected, false);
  assert.equal(state.failedAttacks, 1);
  assert.equal(state.bossHealth, 1, 'The intended finisher never reaches the game');
  assert.equal(state.successfulAttacks, 5);
  assert.equal(state.controllerLedOn, false);
  assert.equal(state.finished, false);
  await io.until(s => s.finished);
  state = await io.state();
  assert.equal(state.phase, 3);
  assert.equal(state.warning, 'Controller disconnected');
  assert.equal(state.unplugProgress, 1);
  const frozenHero = state.heroPose, frozenClock = state.heroClock, runningWorld = state.worldTime, movingBoss = state.bossPose;
  await io.shot('controller-disconnected-boss-windup');
  await io.wait(650);
  state = await io.state();
  assert.equal(state.heroClock, frozenClock);
  assert.deepEqual(state.heroPose, frozenHero, 'The hero stays frozen after the disconnect');
  assert.ok(state.worldTime > runningWorld + .4, 'The game world keeps running after completion');
  assert.notDeepEqual(state.bossPose, movingBoss, 'The boss continues its wind-up and attack animation');
  assert.equal(state.bossHealth, 1);
  assert.equal(await page.evaluate(() => finished), true);
  await io.shot('controller-world-still-running');
};
