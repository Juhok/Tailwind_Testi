module.exports = async function (page, io, assert) {
  let state = await io.state();
  assert.equal(state.kills, 0);
  assert.equal(state.playerClass, 'KNIGHT');
  assert.equal(state.wantedItem, 'SUNCREST HELM');
  await io.drag([320, 139], [104, 140]);
  await io.click(310, 150);
  assert.equal((await io.state()).kills, 0, 'Neither the enemy nor a nonexistent reward can bypass combat');

  await io.click(420, 225);
  state = await io.state();
  assert.equal(state.attacks, 1);
  assert.equal(state.enemy.hp, 1, 'Each enemy takes real damage before defeat');
  assert.equal(state.kills, 0);
  await io.wait(170);
  await io.down(420, 225);
  await io.until(s => s.kills >= 9);
  await io.up();
  state = await io.state();
  assert.equal(state.phase, 0);
  assert.ok(state.kills >= 9 && state.kills < 15);
  assert.equal(state.rareVisible, false);
  assert.equal(state.wantedCollected, false);
  assert.equal(state.finished, false);
  assert.equal(new Set(state.defeatedIds).size, state.kills, 'Each counter increment is a distinct defeated enemy');
  assert.ok(state.junkCounts.filter(n => n > 0).length >= 7, 'The enemies drop visibly varied unwanted items');
  const pausedKills = state.kills;
  await io.wait(350);
  assert.equal((await io.state()).kills, pausedKills, 'Releasing the control stops combat');
  await io.shot('never-loot-unwanted-drops');

  await io.down(420, 225);
  await io.until(s => s.kills >= 40);
  state = await io.state();
  assert.equal(state.phase, 0);
  assert.equal(state.rareVisible, false);
  assert.equal(state.finished, false, 'Even forty defeats do not grant the rare item');
  await io.until(s => s.phase === 1);
  await io.up();
  state = await io.state();
  assert.equal(state.kills, 50);
  assert.equal(state.attacks, 100, 'Fifty individually defeated two-hit enemies');
  assert.deepEqual(state.defeatedIds, Array.from({ length: 50 }, (_, i) => i + 1));
  assert.equal(state.drops.length, 50);
  assert.equal(state.junkCounts.reduce((sum, n) => sum + n, 0), 49);
  assert.equal(state.wantedCollected, false);
  assert.equal(state.finished, false);
  await io.until(s => s.phase === 2);
  await io.shot('never-loot-legendary-drop');
  state = await io.state();
  assert.equal(state.rareItem, 'MOONGLASS CIRCLET');
  assert.notEqual(state.rareItem, state.wantedItem);
  await io.click(420, 225);
  assert.equal((await io.state()).kills, 50, 'The counter stops at exactly fifty');

  await io.drag([320, 139], [405, 120]);
  assert.equal((await io.state()).phase, 2, 'A drop away from the knight does not reveal the equip failure');
  await io.drag([320, 139], [104, 140], { steps: 20 });
  state = await io.state();
  assert.equal(state.phase, 3);
  assert.equal(state.rejected, true);
  assert.equal(state.rareClass, 'SORCERER');
  assert.equal(state.equipped, false);
  assert.equal(state.finished, false, 'The rejected item visibly returns before completion');
  await io.until(s => s.finished);
  state = await io.state();
  assert.equal(state.phase, 4);
  assert.equal(state.kills, 50);
  assert.equal(state.wantedCollected, false);
  assert.equal(state.equipped, false);
  assert.equal(state.item.x, 320);
  assert.equal(await page.evaluate(() => finished), true);
  await io.shot('never-loot-wrong-class');
};
