module.exports = async function (page, io, assert) {
  let state = await io.state();
  assert.equal(state.sliderY, 218);
  assert.equal(state.caught, false);
  await io.drag([257, 101], [240, 190]);
  await io.drag([240, 235], [240, 251]);
  state = await io.state();
  assert.equal(state.phase, 0);
  assert.equal(state.sliderY, 218, 'Wrong object and backward initial pull cannot catch the lining');
  assert.equal(state.finished, false);

  await io.drag([240, 235], [240, 173], { steps: 20 });
  state = await io.state();
  assert.ok(state.zipProgress > .4 && state.zipProgress < .6, 'The tooth rows progressively join behind the actual slider');
  assert.equal(state.caught, false);
  assert.equal(state.finished, false);
  await io.shot('fabric-zipper-partially-closed');
  await io.drag([240, 173], [240, 112], { steps: 20 });
  state = await io.state();
  assert.equal(state.phase, 1, 'The lining catch has its own visible animation');
  assert.equal(state.sliderY, 95);
  assert.equal(state.wedge, 0);
  await io.until(s => s.phase === 2);
  state = await io.state();
  assert.equal(state.catchProgress, 1);
  const initialThickness = state.fabricThickness;
  await io.wait(300);
  assert.equal((await io.state()).wedge, 0, 'The catch does not get worse without a new reverse gesture');
  await io.shot('fabric-zipper-lining-caught');

  await io.drag([240, 112], [240, 83]);
  state = await io.state();
  assert.equal(state.phase, 2, 'Pulling farther up cannot substitute for reversing the zipper');
  assert.equal(state.wedge, 0);
  await io.drag([240, 112], [240, 147], { steps: 18, hold: .45 });
  state = await io.state();
  assert.equal(state.phase, 3);
  assert.ok(state.wedge > .2 && state.wedge < .6, 'The short reverse pull partially bunches the lining');
  assert.ok(state.fabricThickness > initialThickness);
  assert.ok(state.reverseSliderTravel > 0 && state.reverseSliderTravel < 3, 'Fabric grows while the slider barely moves');
  assert.equal(state.finished, false);
  await io.shot('fabric-zipper-reversal-worsens');
  const pullY = state.pull.y;
  await io.drag([240, pullY], [240, 205], { steps: 20, hold: 1 });
  await io.until(s => s.finished);
  state = await io.state();
  assert.equal(state.phase, 5);
  assert.equal(state.wedge, 1);
  assert.equal(state.reverseSliderTravel, 4);
  assert.ok(state.fabricThickness > initialThickness * 3);
  assert.equal(await page.evaluate(() => finished), true);
  await io.shot('fabric-zipper-wedged-tight');
};
